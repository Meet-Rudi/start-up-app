"""
Generates db/migrations/0002_seed_access.sql from the catalogue.

    python -m rudi_platform.access.seed > db/migrations/0002_seed_access.sql

(run from the packages/ directory, or with packages/ on PYTHONPATH). Deterministic: the same
catalogue always gives the same file, which is what lets a test hold the two together. Ids are
written as `{new_id:cat}`; the migration runner replaces each with a fresh id from
rudi_platform.ids.new_id when it applies the file, so each database gets its own (MySQL on
PlanetScale has no stored functions to mint them, decision #46).
"""

from __future__ import annotations

from .catalogue import PERMISSIONS, SEED_ROLES


def _q(text: str) -> str:
    # MySQL reads a backslash in a string literal as an escape; the catalogue has none.
    if "\\" in text:
        raise ValueError(f"a seed text may not contain a backslash: {text!r}")
    return "'" + text.replace("'", "''") + "'"


def _rows(rows: list[str]) -> str:
    return ",\n".join(rows) + ";"


def render() -> str:
    order = {p.key: i for i, p in enumerate(PERMISSIONS)}
    perms = [
        f"  ({{new_id:prm}}, {_q(p.key)}, {_q(p.scope.value)}, {_q(p.description)})"
        for p in PERMISSIONS
    ]
    roles = [
        f"  ({{new_id:rol}}, {_q(r.key)}, {_q(r.name)}, {_q(r.scope.value)}, "
        f"{'TRUE' if r.assignable_by_tenant_admin else 'FALSE'}, TRUE)"
        for r in SEED_ROLES
    ]
    grants: list[str] = []
    for r in SEED_ROLES:
        keys = sorted(r.permissions, key=order.__getitem__)
        grants += [
            "",
            "INSERT INTO access_control_role_permissions (role_id, permission_id)",
            "SELECT r.id, p.id",
            "FROM access_control_roles r",
            "JOIN access_control_permissions p ON p.permission_key IN (",
            ",\n".join(f"  {_q(k)}" for k in keys) + ")",
            f"WHERE r.role_key = {_q(r.key)};",
        ]
    return "\n".join(
        [
            "-- MEET_RUDI platform: 0002, seed permissions, roles and the pooled cell.",
            "-- GENERATED by `python -m rudi_platform.access.seed` from",
            "-- packages/rudi_platform/access/catalogue.py. Do not edit by hand.",
            "-- The runner replaces every {new_id:…} with a fresh id (rudi_platform.ids.new_id).",
            "",
            (
                "INSERT INTO access_control_permissions"
                " (id, permission_key, scope_level, description) VALUES"
            ),
            _rows(perms),
            "",
            (
                "INSERT INTO access_control_roles (id, role_key, display_name,"
                " scope_level, assignable_by_tenant_admin, seed) VALUES"
            ),
            _rows(roles),
            *grants,
            "",
            "INSERT INTO registry_cells (id, slug, kind) VALUES",
            "  ({new_id:cel}, 'pool', 'pooled');",
            "",
        ]
    )


if __name__ == "__main__":
    import sys

    # UTF-8 bytes with LF line ends whatever the console's code page (Windows redirects as cp1252).
    sys.stdout.buffer.write(render().encode("utf-8"))
