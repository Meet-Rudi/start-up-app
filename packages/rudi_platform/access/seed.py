"""
Generates db/migrations/0002_seed_access.sql from the catalogue.

    python -m rudi_platform.access.seed > db/migrations/0002_seed_access.sql

(run from the packages/ directory, or with packages/ on PYTHONPATH). Deterministic: the same
catalogue always gives the same file, which is what lets a test hold the two together. Ids are
minted in the database (public.rudi_new_id) so each environment gets its own.
"""

from __future__ import annotations

from .catalogue import PERMISSIONS, SEED_ROLES


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _rows(rows: list[str]) -> str:
    return ",\n".join(rows) + ";"


def render() -> str:
    order = {p.key: i for i, p in enumerate(PERMISSIONS)}
    perms = [
        f"  (public.rudi_new_id('prm'), {_q(p.key)}, {_q(p.scope.value)}, {_q(p.description)})"
        for p in PERMISSIONS
    ]
    roles = [
        f"  (public.rudi_new_id('rol'), {_q(r.key)}, {_q(r.name)}, {_q(r.scope.value)}, "
        f"{'true' if r.assignable_by_tenant_admin else 'false'}, true)"
        for r in SEED_ROLES
    ]
    grants = [
        f"  ({_q(r.key)}, {_q(k)})"
        for r in SEED_ROLES
        for k in sorted(r.permissions, key=order.__getitem__)
    ]
    return "\n".join(
        [
            "-- MEET_RUDI platform: 0002, seed permissions, roles and the pooled cell.",
            "-- GENERATED by `python -m rudi_platform.access.seed` from",
            "-- packages/rudi_platform/access/catalogue.py. Do not edit by hand.",
            "",
            "INSERT INTO access.permissions (id, key, scope, description) VALUES",
            _rows(perms),
            "",
            "INSERT INTO access.roles (id, key, name, scope, assignable_by_tenant_admin, seed) VALUES",
            _rows(roles),
            "",
            "INSERT INTO access.role_permissions (role_id, permission_id)",
            "SELECT r.id, p.id",
            "FROM (VALUES",
            ",\n".join(grants),
            ") AS m (role_key, permission_key)",
            "JOIN access.roles r ON r.key = m.role_key",
            "JOIN access.permissions p ON p.key = m.permission_key;",
            "",
            "INSERT INTO registry.cells (id, slug, kind) VALUES",
            "  (public.rudi_new_id('cel'), 'pool', 'pooled');",
            "",
        ]
    )


if __name__ == "__main__":
    import sys

    # UTF-8 bytes with LF line ends whatever the console's code page (Windows redirects as cp1252).
    sys.stdout.buffer.write(render().encode("utf-8"))
